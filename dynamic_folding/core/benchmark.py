from __future__ import annotations

import json
import logging
import time
import itertools
from datetime import datetime
from pathlib import Path
from typing import Any

from rich import print
from dynamic_folding.core.pipeline import run_pipeline

logger = logging.getLogger(__name__)

def run_benchmark(root: Path) -> list[dict[str, Any]]:
    """
    Run a multi-dimensional grid search over algorithms, embedders, 
    and hyperparameters (Matrix Mode).
    """
    results_dir = Path("benchmark_results")
    results_dir.mkdir(exist_ok=True)

    # --- Search Space (The Matrix) ---
    # Phase A
    algorithms = ["kmeans", "agglomerative_tree", "hdbscan"]
    embedders = ["fake", "sbert"]
    reducers = ["identity", "pca", "umap"]
    min_cluster_sizes = [2, 4]
    snippet_sizes = [1024, 4096]
    
    # Phase B
    normalizes = [True, False]
    linkages = ["ward", "complete"]
    
    # Generate the full grid
    raw_grid = list(itertools.product(
        algorithms, 
        embedders, 
        reducers,
        min_cluster_sizes, 
        snippet_sizes, 
        normalizes, 
        linkages
    ))
    
    grid = []
    for algo, emb, red, min_size, snip, norm, link in raw_grid:
        # Optimization: Only vary 'linkage' for agglomerative_tree
        if algo != "agglomerative_tree" and link != "ward":
            continue
        # Optimization: 'normalize' has no effect on 'fake' embedder
        if emb == "fake" and norm is False:
            continue
        # Optimization: Reducers are mostly beneficial for HDBSCAN or high-dim embeddings
        # For 'fake' (low-dim), reducers like UMAP/PCA are less critical to test in all combos
        if emb == "fake" and red != "identity":
            continue
            
        grid.append({
            "algorithm": algo,
            "embedding": emb,
            "reducer": red,
            "min_cluster_size": min_size,
            "snippet_size": snip,
            "normalize": norm,
            "linkage": link
        })

    all_results = []
    meta = {
        "dataset_root": str(root.resolve()),
        "timestamp": datetime.now().isoformat(),
        "total_trials": len(grid)
    }

    print(f"\n[bold cyan]Starting Deep Benchmark Matrix for: {root}[/bold cyan]")
    print(f"Testing [bold yellow]{len(grid)}[/bold yellow] unique parameter combinations...\n")

    for i, cfg in enumerate(grid, 1):
        algo = cfg["algorithm"]
        emb = cfg["embedding"]
        red = cfg["reducer"]
        min_size = cfg["min_cluster_size"]
        snip = cfg["snippet_size"]
        norm = cfg["normalize"]
        link = cfg["linkage"]
        
        # Dictionary-based overrides
        overrides = {
            "scanner": {"extractor": "type_aware", "snippet_size": snip},
            "embedding": {"provider": emb, "normalize": norm},
            "reducer": {"provider": red, "n_components": 10},
            "clustering": {"algorithm": algo, "min_cluster_size": min_size, "linkage": link},
            "proposal": {"provider": "two_level", "min_cluster_size": min_size}
        }

        start_time = time.time()
        try:
            # run_pipeline handles merging with defaults automatically
            result = run_pipeline(root, overrides=overrides)
            duration = time.time() - start_time

            # Quality grading (silhouette) is intentionally NOT computed here:
            # silhouette is an evaluation-only instrument and no longer rides on
            # the product contract (ADR 0035). This grid records structural facts
            # only; characterization numbers are regenerated by a standalone script.
            res_entry = {
                **cfg,
                "clusters": len(result.proposal.folders),
                "outliers": len(result.proposal.orphans) if result.proposal.orphans else 0,
                "duration_s": round(duration, 2),
                "timestamp": datetime.now().isoformat()
            }
            all_results.append(res_entry)

            print(f"[{i:03}/{len(grid):03}] "
                  f"clusters:{res_entry['clusters']:3} | outliers:{res_entry['outliers']:3} | "
                  f"{algo:18} | {emb:5} | {red:8} | K_min:{min_size} | Snip:{snip:4} | {duration:.2f}s")

        except Exception as e:
            print(f"[{i:03}/{len(grid):03}] [bold red]FAILED[/bold red] | {algo:18} | {emb:5} | {red:8} | Error: {str(e)[:50]}")

    # Save to disk with Metadata
    report = {
        "metadata": meta,
        "results": all_results
    }
    
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    output_path = results_dir / f"matrix_benchmark_{timestamp}.json"
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(report, f, indent=2)

    # --- Summary ---
    if all_results:
        print(f"\n[bold green]Benchmark Complete![/bold green]")
        print(f"Total Trials: {len(all_results)}")
        print(f"Results saved to: [cyan]{output_path}[/cyan]\n")
        print("Quality grading (silhouette) is not part of this grid — see the "
              "standalone characterization script for Chapter 4 numbers.")

    return all_results
